// The pull installer's script and cloud-config template, which the API renders into the userData of
// a node's rescue (src/node-installer.ts), as a module. The files stay where the image's builder
// and its tests read them; this module is what the Worker bundles. Check it in CI.
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";

const files = {
  INSTALLER_SCRIPT: "../../../infra/node-image/installer/install.sh",
  INSTALLER_CLOUD_CONFIG:
    "../../../infra/node-image/installer/cloud-config.yaml",
};
const source = [
  "// SPDX-License-Identifier: Apache-2.0",
  "// Generated by native/generate-installer.ts from infra/node-image/installer; do not edit.",
  ...(await Promise.all(
    Object.entries(files).map(
      async ([name, path]) =>
        `export const ${name} = ${JSON.stringify(await readFile(new URL(path, import.meta.url), "utf8"))};`,
    ),
  )),
].join("\n");
const contents = await format(source, { parser: "typescript" }),
  target = new URL("../src/node-installer-files.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== contents)
    throw new Error("node-installer-files.generated.ts is stale");
} else await writeFile(target, contents);
