// The release public key as a constant of the Workers that verify releases with it
// (src/release-key.generated.ts): the file apps/node-agent/release-signing.pub, which the agent's
// build reads as its own constant. The key travels with the code of the Worker, so no setting,
// secret or API call changes the key an installed release is verified with. Check it in CI.
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";

const text = await readFile(
  new URL("../../../apps/node-agent/release-signing.pub", import.meta.url),
  "utf8",
);
const key = /^([0-9a-f]{64})\n?$/.exec(text)?.[1];
if (key === undefined)
  throw new Error(
    "apps/node-agent/release-signing.pub holds 64 lower-case hex symbols and a line feed",
  );
const source = [
  "// SPDX-License-Identifier: Apache-2.0",
  "// Generated by native/generate-release-key.ts from apps/node-agent/release-signing.pub; do not edit.",
  `export const RELEASE_PUBLIC_KEY = ${JSON.stringify(key)};`,
].join("\n");
const contents = await format(source, { parser: "typescript" }),
  target = new URL("../src/release-key.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8").catch(() => "")) !== contents)
    throw new Error("release-key.generated.ts is stale");
} else await writeFile(target, contents);
